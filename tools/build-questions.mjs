function addArith(grade, topic, kp, diff, a, b, op) {
  let ans;
  let sign;
  let word;
  if (op === '+') { ans = a + b; sign = '+'; word = '加'; }
  else if (op === '-') { ans = a - b; sign = '−'; word = '减'; }
  else if (op === '*') { ans = a * b; sign = '×'; word = '乘'; }
  else { ans = a / b; sign = '÷'; word = '除以'; }
  if (!Number.isInteger(ans) || ans < 0) throw new Error('坏算术题 ' + a + op + b);
  const text = `${a} ${sign} ${b} = ？`;
  const exp = `${a}${word}${b}等于${ans}。`;
  if ((a + b + (op === '+' ? 1 : 0)) % 3 === 0) {
    fi(grade, '数学', topic, kp, diff, text + ' 只写数字。', [String(ans)], exp);
  } else {
    mc(grade, '数学', topic, kp, diff, text, numericOptions(ans), String(ans), exp);
  }
}

