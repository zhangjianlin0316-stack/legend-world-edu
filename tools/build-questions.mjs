let seq = 1;

function mulberry32(seed) {
  let a = seed >>> 0;
  return function rng() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rng = mulberry32(20261115);

function shuffle(list) {
  const a = list.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function pushQ(q) {
  if (!q.explanation) throw new Error('缺少讲解：' + q.question);
  if (!q.knowledgePoint) throw new Error('缺少知识点：' + q.question);
  if (q.type === 'choice') {
    if (!q.options || q.options.length < 3) throw new Error('选项不够：' + q.question);
    if (new Set(q.options).size !== q.options.length) throw new Error('选项重复：' + q.question + ' / ' + q.options.join('|'));
    if (!q.options.includes(q.answer)) throw new Error('答案不在选项中：' + q.question + ' => ' + q.answer);
  } else if (q.type === 'fill') {
    const ans = Array.isArray(q.answer) ? q.answer : [q.answer];
    if (!ans.length || ans.some((x) => x === undefined || x === '')) throw new Error('填空答案空：' + q.question);
    q.answer = ans;
  } else {
    throw new Error('未知题型');
  }
  q.id = 'q' + String(seq++).padStart(4, '0');
  q.difficulty = Math.max(1, Math.min(5, q.difficulty | 0));
  questions.push(q);
}

function mc(grade, subject, topic, kp, difficulty, question, options, answer, explanation) {
  pushQ({
    grade, subject, topic, knowledgePoint: kp, difficulty,
    type: 'choice', question, options: options.map(String), answer: String(answer), explanation,
  });
}

function fi(grade, subject, topic, kp, difficulty, question, answer, explanation) {
  pushQ({
    grade, subject, topic, knowledgePoint: kp, difficulty,
    type: 'fill', question, answer, explanation,
  });
}

function distract(correct, pool, count = 3) {
  const opts = [String(correct)];
  for (const item of shuffle(pool)) {
    const s = String(item);
    if (!opts.includes(s)) opts.push(s);
    if (opts.length >= count + 1) break;
  }
  if (opts.length < count + 1) throw new Error('干扰项不够：' + correct);
  return shuffle(opts);
}

function fmt(n) {
  if (typeof n === 'string') return n;
  const r = Math.round(n * 1000) / 1000;
  if (Object.is(r, -0)) return '0';
  return String(r);
}

function numericOptions(answer) {
  const ans = Number(answer);
  const seeds = [1, -1, 2, -2, 10, -10, 3, -3, 5, -5, 4, 6, -4, 8, -8, 20, -20];
  const set = new Set([fmt(ans)]);
  for (const d of shuffle(seeds)) {
    const v = Math.round((ans + d) * 1000) / 1000;
    if (v < 0) continue;
    set.add(fmt(v));
    if (set.size >= 4) break;
  }
  let k = 7;
  while (set.size < 4) {
    set.add(fmt(ans + k));
    k += 1;
  }
  return shuffle([...set]);
}

function decimalOptions(answer) {
  const ans = Math.round(Number(answer) * 10) / 10;
  const set = new Set([fmt(ans)]);
  const deltas = [0.1, -0.1, 0.2, -0.2, 0.5, -0.5, 1, -1, 0.3, -0.3, 1.1, 0.4];
  for (const d of shuffle(deltas)) {
    const v = Math.round((ans + d) * 10) / 10;
    if (v < 0) continue;
    set.add(fmt(v));
    if (set.size >= 4) break;
  }
  let k = 2;
  while (set.size < 4) {
    set.add(fmt(Math.round((ans + k) * 10) / 10));
    k += 1;
  }
  return shuffle([...set]);
}

