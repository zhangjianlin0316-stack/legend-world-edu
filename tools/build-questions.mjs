function rebalanceDifficulty() {
  const groups = new Map();
  for (const q of questions) {
    const key = q.grade + '-' + q.subject;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(q);
  }
  for (const list of groups.values()) {
    list.sort((a, b) => (a.difficulty - b.difficulty) || (a.type === b.type ? 0 : a.type === 'fill' ? 1 : -1) || a.id.localeCompare(b.id));
    const n = list.length;
    list.forEach((q, i) => {
      q.difficulty = 1 + Math.min(4, Math.floor((i * 5) / n));
    });
  }
}

function validate() {
  const by = {};
  for (const q of questions) {
    const key = `${q.grade}-${q.subject}`;
    by[key] = by[key] || { n: 0, choice: 0, fill: 0, diff: {}, topics: new Set() };
    const b = by[key];
    b.n += 1;
    b[q.type] += 1;
    b.diff[q.difficulty] = (b.diff[q.difficulty] || 0) + 1;
    b.topics.add(q.topic);
  }
  const problems = [];
  for (let g = 1; g <= 6; g++) {
    for (const s of ['语文', '数学']) {
      const b = by[`${g}-${s}`];
      if (!b || b.n < 50) problems.push(`${g}年级${s}只有 ${b ? b.n : 0} 题`);
      if (!b || b.choice < 1 || b.fill < 1) problems.push(`${g}年级${s}题型不完整`);
      for (let d = 1; d <= 5; d++) {
        if (!b || !b.diff[d]) problems.push(`${g}年级${s}缺少难度 ${d}`);
      }
    }
  }
  const ids = new Set(questions.map((q) => q.id));
  if (ids.size !== questions.length) problems.push('题目 id 重复');
  if (problems.length) {
    console.error(problems.join('\n'));
    console.error(JSON.stringify(by, (k, v) => (v instanceof Set ? [...v] : v), 2));
    process.exit(1);
  }
  for (const [k, b] of Object.entries(by)) {
    console.log(`${k}: ${b.n} 题（选择 ${b.choice} / 填空 ${b.fill}）难度 ${JSON.stringify(b.diff)} 主题 ${[...b.topics].join('、')}`);
  }
  console.log('合计', questions.length, '题');
}

function loadExtra() {
  const p = path.join(root, 'data', 'extra-questions.json');
  if (!fs.existsSync(p)) return [];
  const extra = JSON.parse(fs.readFileSync(p, 'utf8'));
  if (!Array.isArray(extra)) throw new Error('extra-questions.json 必须是数组');
  return extra;
}

